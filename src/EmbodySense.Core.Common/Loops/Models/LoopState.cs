namespace EmbodySense.Core.Common.Loops.Models;

/// <summary>
/// Identifies the supported loop state values.
/// </summary>
public enum LoopState
{
    /// <summary>
    /// Identifies the unknown loop state.
    /// </summary>
    Unknown = 0,
    /// <summary>
    /// Identifies the enabled loop state.
    /// </summary>
    Enabled,
    /// <summary>
    /// Identifies the disabled loop state.
    /// </summary>
    Disabled
}
